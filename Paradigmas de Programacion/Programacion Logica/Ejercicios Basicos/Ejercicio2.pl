% 2) juan.
% Rta: es un atomo ya que empieza con minúscula. Los atomos en Prolog son constantes que representan un valor específico, por lo que "juan" es un atomo que representa a una persona específica llamada Juan.

% 3) Persona.
% Rta: es una variable ya que empieza con mayúscula. Las variables en Prolog pueden tomar cualquier valor, por lo que "Persona" puede representar cualquier cosa, incluyendo a Juan o a cualquier otra persona.

% 4) persona(juan).
% Rta: es un termino compuesto. Un término compuesto en Prolog es una estructura que consta de un functor (en este caso "persona") y uno o más argumentos (en este caso "juan"). Este término representa la relación de que "juan" es una persona.

% 5) 20.
% Rta: es un número. En Prolog, los números se representan como constantes numéricas, por lo que "20" es un número que representa el valor veinte.

